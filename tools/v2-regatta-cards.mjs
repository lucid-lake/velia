// Bakes the Regatta course cards (step D4): each shipped course's card art (v2/regatta/cardArt.js
// cardSvg: the course on a navy chart ground, the marks 1 … F, the rounding symbols, the wind arrow) rendered by headless Chromium
// at 1× and 2× into v2/regatta/cards/*.png, and v2/regatta/cards.js (the files' URLs for the hub, and each source's hash). The
// hub and the Custom sheet show the PNGs (srcset 1x, 2x); the words beside them stay HTML. Re-run after a course JSON or the art
// changes; v2/tests/regatta-cards.test.mjs fails while cards.js is stale.
//   node tools/v2-regatta-cards.mjs           bake the PNGs and cards.js
//   node tools/v2-regatta-cards.mjs --check   exit 1 when a source changed since the bake (no browser)
//   node tools/v2-regatta-cards.mjs --twice   bake, bake again, and fail on any byte that differs (the renderer's determinism)
import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { courseFor, courseIds } from '../src/sim/race/course.js';
import { cardSvg, CARD_KINDS } from '../v2/regatta/cardArt.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const OUT_DIR = fileURLToPath(new URL('../v2/regatta/cards/', import.meta.url));
export const OUT_JS = fileURLToPath(new URL('../v2/regatta/cards.js', import.meta.url));
export const WATERS = ['tahoe-emerald'];
export const DENSITIES = [1, 2];
export const COURSE_KINDS = ['card', 'tile', 'plate'];
const CHROME = process.env.LAKESHORE_CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

// every source the bake renders: { key, file stem, kind, svg }
export function sources() {
  const out = [];
  for (const w of WATERS) for (const id of courseIds(w)) {
    const c = courseFor(w, id, { laps: 1 });
    for (const kind of COURSE_KINDS) out.push({ waters: w, id, kind, stem: `${id}-${kind}`, svg: cardSvg(c, { kind }) });
  }
  out.push({ waters: null, id: 'board', kind: 'board', stem: 'board', svg: cardSvg(null, { kind: 'board' }) });
  return out;
}
export const hashOf = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);

export function cardsJs(list = sources()) {
  const url = (stem, d) => `new URL('./cards/${stem}@${d}x.png', import.meta.url).href`;
  const pair = (stem) => `[${DENSITIES.map((d) => url(stem, d)).join(', ')}]`;
  const lines = ['// Generated by tools/v2-regatta-cards.mjs: the course cards baked at 1× and 2× (v2/regatta/cardArt.js). Do not edit; re-run the tool.',
    '// CARDS[waters][course] = { card, tile, plate: [1×, 2×] } (URLs); BOARD the course board\'s chart ground; SOURCES each file\'s source hash.'];
  const by = {};
  for (const s of list) if (s.waters) ((by[s.waters] ??= {})[s.id] ??= {})[s.kind] = s.stem;
  lines.push('export const CARDS = {');
  for (const [w, cs] of Object.entries(by)) {
    lines.push(`  '${w}': {`);
    for (const [id, k] of Object.entries(cs)) lines.push(`    '${id}': { ${COURSE_KINDS.map((kind) => `${kind}: ${pair(k[kind])}`).join(', ')} },`);
    lines.push('  },');
  }
  lines.push('};');
  lines.push(`export const BOARD = ${pair('board')};`);
  lines.push(`export const SOURCES = ${JSON.stringify(Object.fromEntries(list.map((s) => [s.stem, hashOf(s.svg)])), null, 1).replace(/\n/g, ' ').replace(/\s+/g, ' ')};`);
  lines.push(`export const CARD_SIZES = ${JSON.stringify(Object.fromEntries(Object.entries(CARD_KINDS).map(([k, v]) => [k, [v.w, v.h]])))};`);
  return `${lines.join('\n')}\n`;
}

// the page Chromium renders: the hub's two faces (the repo's own woff2), the SVG at its CSS size, nothing else
function pageHtml(svg) {
  const font = (wgt) => `@font-face{font-family:'Atkinson Hyperlegible Next';font-weight:${wgt};src:url(data:font/woff2;base64,${readFileSync(`${ROOT}fonts/atkinson-hyperlegible-next-latin-${wgt}.woff2`).toString('base64')}) format('woff2')}`;
  return `<!doctype html><meta charset="utf-8"><style>${font(400)}${font(500)}html,body{margin:0;background:#1c2340}svg{display:block}</style>${svg}`;
}
export async function bake({ list = sources() } = {}) {
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ executablePath: existsSync(CHROME) ? CHROME : undefined, headless: true, args: ['--font-render-hinting=none', '--disable-lcd-text', '--force-color-profile=srgb'] });
  const files = {};
  try {
    for (const d of DENSITIES) {
      const ctx = await browser.newContext({ deviceScaleFactor: d, viewport: { width: 420, height: 260 } });
      const page = await ctx.newPage();
      for (const s of list) {
        const K = CARD_KINDS[s.kind];
        await page.setContent(pageHtml(s.svg));
        await page.evaluate(() => document.fonts.ready);
        files[`${s.stem}@${d}x.png`] = await page.screenshot({ clip: { x: 0, y: 0, width: K.w, height: K.h }, type: 'png', animations: 'disabled' });
      }
      await ctx.close();
    }
  } finally { await browser.close(); }
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const list = sources(), js = cardsJs(list);
  if (process.argv.includes('--check')) {
    let now = ''; try { now = readFileSync(OUT_JS, 'utf8'); } catch { /* none yet */ }
    if (now !== js) { console.error('cards.js is stale: run node tools/v2-regatta-cards.mjs'); process.exit(1); }
    console.log('cards.js is current');
  } else {
    const a = await bake({ list });
    if (process.argv.includes('--twice')) {
      const b = await bake({ list });
      const diff = Object.keys(a).filter((k) => !a[k].equals(b[k]));
      if (diff.length) { console.error(`not deterministic: ${diff.join(', ')}`); process.exit(1); }
      console.log(`deterministic: ${Object.keys(a).length} files byte-identical over two bakes`);
    }
    mkdirSync(OUT_DIR, { recursive: true });
    let bytes = 0;
    for (const [f, buf] of Object.entries(a)) { writeFileSync(`${OUT_DIR}${f}`, buf); bytes += buf.length; }
    writeFileSync(OUT_JS, js);
    console.log(`wrote ${Object.keys(a).length} PNGs (${(bytes / 1024).toFixed(0)} KB) and ${OUT_JS}`);
  }
}
